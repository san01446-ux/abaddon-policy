function initCommandPage() {
  const grid = document.getElementById("command-grid");
  if (!grid) return;

  const search = document.getElementById("command-search");
  const tabs = document.getElementById("category-tabs");
  const meta = document.getElementById("command-meta");
  const empty = document.getElementById("empty-state");
  const modeButton = document.querySelector("[data-command-mode]");
  const resetButton = document.querySelector("[data-command-reset]");
  const goalButtons = [...document.querySelectorAll("[data-command-goal]")];
  const copyButtons = [...document.querySelectorAll("[data-copy-command]")];
  const toast = document.getElementById("copy-toast");

  let category = "전체";
  let goal = "all";
  let representativeOnly = true;

  async function copyText(value) {
    const text = String(value || "").trim();
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
    } catch (_error) {
      const area = document.createElement("textarea");
      area.value = text;
      area.style.position = "fixed";
      area.style.opacity = "0";
      document.body.appendChild(area);
      area.select();
      document.execCommand("copy");
      area.remove();
    }
    if (toast) {
      toast.textContent = `${text} 복사 완료`;
      toast.classList.add("show");
      window.clearTimeout(toast._timer);
      toast._timer = window.setTimeout(() => toast.classList.remove("show"), 1800);
    }
  }

  function matchesGoal(item) {
    if (goal === "all") return true;
    const definition = COMMAND_GOALS[goal];
    if (!definition) return true;
    const text = commandText(item);
    return definition.keywords.some((keyword) => text.includes(keyword.toLocaleLowerCase("ko-KR")));
  }

  function renderTabs() {
    tabs.innerHTML = "";
    categories.forEach((name) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "category-button" + (name === category ? " active" : "");
      button.textContent = name;
      button.addEventListener("click", () => {
        category = name;
        goal = "all";
        goalButtons.forEach((goalButton) => goalButton.classList.toggle("active", goalButton.dataset.commandGoal === "all"));
        renderTabs();
        renderCommands();
      });
      tabs.appendChild(button);
    });
  }

  function updateModeButton() {
    if (!modeButton) return;
    modeButton.textContent = representativeOnly ? "전체 명령 보기" : "대표 명령만 보기";
    modeButton.setAttribute("aria-pressed", String(!representativeOnly));
  }

  function createCommandCard(item) {
    const card = document.createElement("article");
    card.className = "command-card" + (isFeaturedCommand(item) ? " featured" : "");

    const top = document.createElement("div");
    top.className = "command-top";
    const code = document.createElement("code");
    code.textContent = item.cmd;
    const labels = document.createElement("div");
    labels.className = "command-labels";
    if (isFeaturedCommand(item)) {
      const featured = document.createElement("span");
      featured.className = "featured-label";
      featured.textContent = "대표";
      labels.appendChild(featured);
    }
    const label = document.createElement("span");
    label.className = "category-label";
    label.textContent = item.c;
    labels.appendChild(label);
    top.append(code, labels);

    const desc = document.createElement("p");
    desc.textContent = item.d;

    const footer = document.createElement("div");
    footer.className = "command-card-footer";
    const primary = primaryCommand(item.cmd);
    const copy = document.createElement("button");
    copy.type = "button";
    copy.className = "command-copy";
    copy.textContent = `${primary} 복사`;
    copy.addEventListener("click", () => copyText(primary));
    const hint = document.createElement("span");
    hint.textContent = item.cmd.includes("·") ? "같은 기능의 명령어를 한 카드에 묶었습니다." : "Discord 채팅창에 붙여넣으세요.";
    footer.append(copy, hint);

    card.append(top, desc, footer);
    return card;
  }

  function renderCommands() {
    const query = (search.value || "").trim().toLocaleLowerCase("ko-KR");
    const defaultLanding = !query && category === "전체" && goal === "all";
    const filtered = commands.filter((item) => {
      const categoryOk = category === "전체" || item.c === category;
      const queryOk = !query || commandText(item).includes(query);
      const goalOk = matchesGoal(item);
      const featuredOk = !representativeOnly || !defaultLanding || isFeaturedCommand(item);
      return categoryOk && queryOk && goalOk && featuredOk;
    });

    grid.innerHTML = "";
    filtered.forEach((item) => grid.appendChild(createCommandCard(item)));

    const modeText = defaultLanding && representativeOnly ? "대표 명령" : "검색 결과";
    const goalText = goal !== "all" ? ` · 목적: ${COMMAND_GOALS[goal].label}` : "";
    meta.textContent = `${modeText} ${filtered.length}개 표시 · 전체 ${commands.length}개${goalText}`;
    empty.style.display = filtered.length ? "none" : "block";
    updateModeButton();
  }

  search.addEventListener("input", renderCommands);

  goalButtons.forEach((button) => {
    button.addEventListener("click", () => {
      goal = button.dataset.commandGoal || "all";
      category = "전체";
      search.value = "";
      goalButtons.forEach((item) => item.classList.toggle("active", item === button));
      renderTabs();
      renderCommands();
      document.getElementById("command-browser")?.scrollIntoView({ behavior: "smooth", block: "start" });
    });
  });

  copyButtons.forEach((button) => button.addEventListener("click", () => copyText(button.dataset.copyCommand)));

  modeButton?.addEventListener("click", () => {
    representativeOnly = !representativeOnly;
    if (!representativeOnly) {
      goal = "all";
      goalButtons.forEach((item) => item.classList.toggle("active", item.dataset.commandGoal === "all"));
    }
    renderCommands();
  });

  resetButton?.addEventListener("click", () => {
    category = "전체";
    goal = "all";
    representativeOnly = true;
    search.value = "";
    goalButtons.forEach((item) => item.classList.toggle("active", item.dataset.commandGoal === "all"));
    renderTabs();
    renderCommands();
  });

  renderTabs();
  renderCommands();
}


function normalizeFeedBase(value) {
  return String(value || "").trim().replace(/\/+$/, "");
}

function formatLiveTime(value) {
  if (!value) return "방금 전";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "시간 미상";
  return new Intl.DateTimeFormat("ko-KR", {
    month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit"
  }).format(date);
}

function eventRune(type) {
  if (type === "enhance") return "⚒";
  if (type === "announcement") return "☩";
  if (type === "system") return "†";
  return "◆";
}

