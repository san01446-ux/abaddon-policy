function commandText(item) {
  return `${item.cmd} ${item.d} ${item.c}`.toLocaleLowerCase("ko-KR");
}

function primaryCommand(commandLine) {
  const first = String(commandLine || "").split("·")[0].trim();
  return first.replace(/\s+[\[<(].*$/, "").trim();
}

function isFeaturedCommand(item) {
  return FEATURED_PREFIXES.some((prefix) => item.cmd.startsWith(prefix));
}

